"""Generate ssm_params.h for the firmware from RomRaider's log_defs.xml.

    python3 gen_params.py [LOG_DEFS_XML] OUTPUT.h

Run by the build (main/CMakeLists.txt). The table is derived from log_defs.xml, which is GPL and not
part of this repo, so the generated header isn't committed either.

For each SSM base parameter it lists the address, length and which bit of the ECU's init reply says
it is supported - everything the firmware needs to build the same read request defs.py does
(supported_by + request_addresses). The names and scalings stay on the computer: the firmware
records raw bytes and ssmraw.py decodes them with defs.py.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import defs  # noqa: E402


def main() -> int:
    if len(sys.argv) not in (2, 3):
        print(__doc__)
        return 2
    xml = sys.argv[1] if len(sys.argv) == 3 else None
    out = Path(sys.argv[-1])
    params = defs.load(xml)
    lines = [
        "// Generated by gen_params.py from RomRaider's log_defs.xml - do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint32_t address;",
        "    uint8_t length;        // bytes",
        "    uint8_t support_byte;  // supported if init[support_byte + 7] has bit (support_bit - 1) set",
        "    uint8_t support_bit;",
        "} ssm_param_t;",
        "",
        "static const ssm_param_t SSM_PARAMS[] = {",
    ]
    for p in params:
        lines.append(f"    {{0x{p.address:06X}, {p.length}, {p.support_byte}, {p.support_bit}}},  // {p.name}")
    lines += ["};", "", "#define SSM_PARAM_COUNT (sizeof SSM_PARAMS / sizeof *SSM_PARAMS)", ""]
    text = "\n".join(lines)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
